export const optionByKey = (key) => OPTIONS.find((o) => o.key === key);

export function nextMonth(today = new Date()) {
  const d = new Date(today.getFullYear(), today.getMonth() + 1, 1);
  return { year: d.getFullYear(), month: d.getMonth() };
}

export const daysInMonth = (year, month) => new Date(year, month + 1, 0).getDate();

// 0 = Senin ... 6 = Minggu
export const weekdayIndex = (year, month, day) =>
  (new Date(year, month, day).getDay() + 6) % 7;

const WIDTH = 1170;
const HEIGHT = 2532;
const CELL = 144;
const FONT = '-apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif';

export function drawSchedule(canvas, { name, year, month, entries, partners = {} }) {
  canvas.width = WIDTH;
  canvas.height = HEIGHT;
  const ctx = canvas.getContext('2d');

  ctx.fillStyle = '#0b0e14';
  ctx.fillRect(0, 0, WIDTH, HEIGHT);

  const total = daysInMonth(year, month);
  const offset = weekdayIndex(year, month, 1);
  const rows = Math.ceil((offset + total) / 7);
  const gridW = CELL * 7;
  const left = (WIDTH - gridW) / 2;
  const headerH = 330;
  const top = (HEIGHT - (headerH + rows * CELL)) / 2;

  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';

  ctx.fillStyle = '#4da3ff';
  ctx.font = `700 42px ${FONT}`;
  ctx.fillText('JADWAL SHIFT SOC', WIDTH / 2, top + 30);

  ctx.fillStyle = '#ffffff';
  ctx.font = `800 80px ${FONT}`;
  ctx.fillText(name.toUpperCase(), WIDTH / 2, top + 120, gridW);

  ctx.fillStyle = '#c9a0ff';
  ctx.font = `700 40px ${FONT}`;
  ctx.fillText(`${MONTH_NAMES[month]} ${year}`, WIDTH / 2, top + 205);

  ctx.font = `700 26px ${FONT}`;
  DAY_NAMES.forEach((d, i) => {
    ctx.fillStyle = i >= 5 ? '#ff6b6b' : '#8b94a3';
    ctx.fillText(d, left + i * CELL + CELL / 2, top + 290);
  });

  const gridTop = top + headerH;
  for (let day = 1; day <= total; day++) {
    const idx = offset + day - 1;
    const col = idx % 7;
    const x = left + col * CELL;
    const y = gridTop + Math.floor(idx / 7) * CELL;
    const opt = optionByKey(entries[day]);

    ctx.fillStyle = opt ? opt.bg : '#121722';
    ctx.fillRect(x, y, CELL, CELL);
    ctx.strokeStyle = opt ? opt.border : '#1d2431';
    ctx.lineWidth = 2;
    ctx.strokeRect(x + 1, y + 1, CELL - 2, CELL - 2);

    ctx.textAlign = 'left';
    ctx.fillStyle = col >= 5 ? '#ff6b6b' : '#e6e9ef';
    ctx.font = `700 24px ${FONT}`;
    ctx.fillText(String(day), x + 14, y + 24);

    if (opt) {
      ctx.textAlign = 'center';
      ctx.fillStyle = opt.fg;
      ctx.font = `800 ${opt.label.length > 3 ? 40 : 50}px ${FONT}`;
      const names = [partners[day]?.L1, partners[day]?.L2].filter(Boolean);
      const labelY = names.length === 2 ? y + 58 : y + CELL / 2 + (names.length ? 4 : 14);
      ctx.fillText(opt.label, x + CELL / 2, labelY, CELL - 16);
      ctx.fillStyle = '#8b94a3';
      if (names.length === 2) {
        ctx.font = `700 22px ${FONT}`;
        ctx.fillText(names[0], x + CELL / 2, y + 102, CELL - 12);
        ctx.fillText(names[1], x + CELL / 2, y + 126, CELL - 12);
      } else if (names.length === 1) {
        ctx.font = `700 26px ${FONT}`;
        ctx.fillText(names[0], x + CELL / 2, y + CELL - 28, CELL - 12);
      }
    }
  }

  ctx.textAlign = 'center';
  ctx.fillStyle = '#2b3342';
  ctx.font = `500 22px ${FONT}`;
  ctx.fillText('Generated by Jadwal SOC', WIDTH / 2, gridTop + rows * CELL + 50);
}
